local function get_kicks(piece, from, to)
    if piece == "O" then
        return {{0, 0}}
    end

    local is_180 = (to-from)%4 == 2
    local key = from..">"..to

    if piece == "I" then
        return (is_180 and kicks.I180 or kicks.I)[key]
    end

    return (is_180 and kicks.normal180 or kicks.normal)[key]
end

